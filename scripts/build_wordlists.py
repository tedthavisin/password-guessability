"""Build prototype/wordlists.js from the raw lists in data/raw/.

Usage (from the repo root):
    bash scripts/fetch_data.sh
    python3 -I scripts/build_wordlists.py

The prototype loads wordlists.js with a <script> tag, so it works from file://
without a web server. Node scripts load the same file with require().
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "prototype" / "wordlists.js"

SOURCES = {
    "passwords": {
        "file": "xato-top100k.txt",
        "name": "xato.net 10-million-password list, top 100,000 (SecLists)",
        "url": "https://github.com/danielmiessler/SecLists/blob/master/Passwords/Common-Credentials/xato-net-10-million-passwords-100000.txt",
    },
    "english": {
        "file": "english-20k.txt",
        "name": "20,000 most common English words (google-10000-english)",
        "url": "https://github.com/first20hours/google-10000-english/blob/master/20k.txt",
    },
}


def load(path: pathlib.Path) -> list[str]:
    """Read one entry per line, keep first occurrence order, drop blanks and non-printable ASCII."""
    seen, out = set(), []
    for line in path.read_text(encoding="latin-1").splitlines():
        word = line.rstrip("\r")
        if not word or word in seen:
            continue
        if not all(32 <= ord(c) < 127 for c in word):
            continue
        seen.add(word)
        out.append(word)
    return out


def main() -> None:
    data = {"sources": {}}
    for key, src in SOURCES.items():
        words = load(RAW / src["file"])
        data[key] = "\n".join(words)
        data["sources"][key] = {"name": src["name"], "url": src["url"], "count": len(words)}
        print(f"{key}: {len(words):,} entries from {src['file']}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(data, ensure_ascii=True)
    OUT.write_text(
        "// Generated by scripts/build_wordlists.py. Do not edit by hand.\n"
        "(function (root) {\n"
        f"  var data = {payload};\n"
        "  if (typeof module === 'object' && module.exports) module.exports = data;\n"
        "  else root.WORDLISTS = data;\n"
        "})(typeof self !== 'undefined' ? self : this);\n",
        encoding="ascii",
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
